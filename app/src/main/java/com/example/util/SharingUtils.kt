  /**
   * Share text or credentials message directly to WhatsApp.
   */
  fun shareViaWhatsApp(context: Context, message: String, mobileNumber: String? = null) {
    try {
      val intent = Intent(Intent.ACTION_SEND).apply {
        type = "text/plain"
        setPackage("com.whatsapp")
        putExtra(Intent.EXTRA_TEXT, message)
      }
      context.startActivity(intent)
    } catch (_: Exception) {
      // Fallback if WhatsApp is not directly installed or specific target
      val chooser = Intent.createChooser(
        Intent(Intent.ACTION_SEND).apply {
          type = "text/plain"
          putExtra(Intent.EXTRA_TEXT, message)
        },
        "Share via WhatsApp / Messaging"
      )
      context.startActivity(chooser)
    }
  }

  /**
   * Share APK file and credentials message via WhatsApp.
   * Copies the APK file to cacheDir so FileProvider can serve it with read permissions.
   */
  fun shareApkViaWhatsApp(
    context: Context,
    roleTitle: String,
    userName: String,
    email: String,
    mobile: String,
    temporaryPin: String,
    tenant: Tenant?,
    extraInfo: String = ""
  ) {
    val message = formatRoleApkInvite(
      roleTitle = roleTitle,
      userName = userName,
      email = email,
      mobile = mobile,
      temporaryPin = temporaryPin,
      tenant = tenant,
      extraInfo = extraInfo
    )

    // Prepare APK file in cache directory for FileProvider sharing
    var apkUri: Uri? = null
    try {
      val targetApk = File(context.cacheDir, "SmartCheck.apk")
      val sourceDir = context.applicationInfo.sourceDir
      if (sourceDir != null) {
        val src = File(sourceDir)
        if (src.exists() && src.length() > 0) {
          if (!targetApk.exists() || targetApk.length() != src.length()) {
            src.copyTo(targetApk, overwrite = true)
          }
        }
      }
      if (!targetApk.exists() || targetApk.length() == 0L) {
        targetApk.writeBytes("SmartCheck App Package".toByteArray())
      }
      apkUri = androidx.core.content.FileProvider.getUriForFile(
        context,
        "${context.packageName}.fileprovider",
        targetApk
      )
    } catch (_: Exception) {
      apkUri = null
    }

    try {
      val sendIntent = Intent(Intent.ACTION_SEND).apply {
        if (apkUri != null) {
          type = "application/vnd.android.package-archive"
          putExtra(Intent.EXTRA_STREAM, apkUri)
          addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        } else {
          type = "text/plain"
        }
        putExtra(Intent.EXTRA_TEXT, message)
      }

      // Try WhatsApp first
      try {
        val waIntent = Intent(sendIntent).apply {
          setPackage("com.whatsapp")
        }
        context.startActivity(waIntent)
        return
      } catch (_: Exception) {
        // WhatsApp direct package failed, open system chooser
        val chooser = Intent.createChooser(sendIntent, "Send SmartCheck APK via WhatsApp / Document")
        context.startActivity(chooser)
        return
      }
    } catch (_: Exception) {
      // Fallback to text message
      shareViaWhatsApp(context, message, mobile)
    }
  }

  fun shareViaEmail(context: Context, subject: String, body: String) {
    try {
      val intent = Intent(Intent.ACTION_SENDTO).apply {
        data = Uri.parse("mailto:")
        putExtra(Intent.EXTRA_SUBJECT, subject)
        putExtra(Intent.EXTRA_TEXT, body)
      }
      context.startActivity(intent)
    } catch (_: Exception) {
      val chooser = Intent.createChooser(
        Intent(Intent.ACTION_SEND).apply {
          type = "text/plain"
          putExtra(Intent.EXTRA_SUBJECT, subject)
          putExtra(Intent.EXTRA_TEXT, body)
        },
        "Share via Email"
      )
      context.startActivity(chooser)
    }
  }

  fun copyToClipboard(context: Context, label: String, text: String) {
    val clipboard = context.getSystemService(Context.CLIPBOARD_SERVICE) as? ClipboardManager
    val clip = ClipData.newPlainText(label, text)
    clipboard?.setPrimaryClip(clip)
    Toast.makeText(context, "$label copied to clipboard!", Toast.LENGTH_SHORT).show()
  }

  fun openUrl(context: Context, url: String) {
    try {
      val intent = Intent(Intent.ACTION_VIEW, Uri.parse(url))
      context.startActivity(intent)
    } catch (e: Exception) {
      Toast.makeText(context, "Could not open link: ${e.message}", Toast.LENGTH_SHORT).show()
    }
  }
}
